import { useCallback, useEffect, useRef, useState } from 'react';
import JsBarcode from 'jsbarcode';
import QRCode from 'qrcode';
import { validateValue } from '../../lib/barcode.js';
import './BarcodeView.css';

/** @typedef {import('../../lib/barcode.js').BarcodeFormat} BarcodeFormat */

const JSBARCODE_FORMAT = {
  EAN_13: 'EAN13',
  EAN_8: 'EAN8',
  UPC_A: 'UPC',
  CODE_128: 'CODE128',
  CODE_39: 'CODE39',
  ITF: 'ITF',
};

function groupInFours(value) {
  return value.match(/.{1,4}/gu)?.join(' ') ?? '';
}

function Fallback({ value }) {
  return (
    <div className="barcode-view" role="alert">
      <p className="barcode-view__fallback-text">
        The barcode couldn't be drawn. Read this number to the cashier:
      </p>
      <p className="barcode-view__fallback-number">{groupInFours(value)}</p>
    </div>
  );
}

function OneD({ value, format, onError }) {
  const ref = useRef(null);
  useEffect(() => {
    try {
      JsBarcode(ref.current, value, {
        format: JSBARCODE_FORMAT[format],
        displayValue: false,
        margin: 20, // px at JsBarcode's module width of 2 = 10 modules quiet zone each side
        background: '#ffffff',
        lineColor: '#000000',
      });
      const svg = ref.current;
      svg.setAttribute('shape-rendering', 'crispEdges');
      svg.setAttribute('preserveAspectRatio', 'xMidYMid meet');
      svg.removeAttribute('width');
      svg.removeAttribute('height');
    } catch {
      onError();
    }
  }, [value, format, onError]);
  return <svg ref={ref} aria-hidden="true" />;
}

function Qr({ value, onError }) {
  const holder = useRef(null);
  useEffect(() => {
    let cancelled = false;
    QRCode.toString(value, { type: 'svg', margin: 2 })
      .then((markup) => {
        if (cancelled || !holder.current) return;
        // The markup is generated by the qrcode library (paths only), but the value is
        // user-supplied, so parse it and append the element rather than injecting HTML.
        const svg = new DOMParser().parseFromString(markup, 'image/svg+xml').documentElement;
        if (svg.nodeName.toLowerCase() !== 'svg') throw new Error('bad qr svg');
        svg.setAttribute('shape-rendering', 'crispEdges');
        svg.removeAttribute('width');
        svg.removeAttribute('height');
        holder.current.replaceChildren(document.importNode(svg, true));
      })
      .catch(() => {
        if (!cancelled) onError();
      });
    return () => {
      cancelled = true;
    };
  }, [value, onError]);
  return <div ref={holder} />;
}

/**
 * Black-on-white barcode with a readable number. Falls back to a large number if it cannot draw.
 * @param {{ value: string, format: BarcodeFormat }} props
 */
export default function BarcodeView({ value, format }) {
  const [failedKey, setFailedKey] = useState(null);
  const key = `${format}:${value}`;
  const onError = useCallback(() => setFailedKey(key), [key]);

  if (!validateValue(value, format).ok || failedKey === key) {
    return <Fallback value={value} />;
  }
  const isQr = format === 'QR_CODE';
  return (
    <div className="barcode-view">
      <div
        className={`barcode-view__art${isQr ? ' barcode-view__art--qr' : ''}`}
        role="img"
        aria-label={`Barcode for ${value}`}
      >
        {isQr ? (
          <Qr value={value} onError={onError} />
        ) : (
          <OneD value={value} format={format} onError={onError} />
        )}
      </div>
      <p className="barcode-view__number">{groupInFours(value)}</p>
    </div>
  );
}
